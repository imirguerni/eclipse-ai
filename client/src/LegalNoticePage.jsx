const LegalNoticePage = ({ onBack, onContactClick, onShowPrivacy }) => {
  const { i18n } = useTranslation();

  useEffect(() => {
    window.scrollTo(0, 0);
  }, []);

  const language = (
    i18n.resolvedLanguage ||
    i18n.language ||
    'fr'
  ).toLowerCase().split(/[-_]/)[0];

  const content = translations[language] || translations.fr;

  return (
    <div className="terms-wrapper">
      <div className="terms-container">
        <button onClick={onBack} className="btn-back">
          {content.back}
        </button>

        <header className="terms-header">
          <h1>{content.title}</h1>
          <p>{content.updated}</p>
        </header>

        <div className="terms-content">
          {content.sections.map((section, index) => (
            <section className="terms-section" key={index}>
              <h2>{section.title}</h2>

              {section.paragraphs?.map((paragraph, paragraphIndex) => (
                <p key={paragraphIndex}>{paragraph}</p>
              ))}

              {section.bullets && (
                <ul>
                  {section.bullets.map((bullet, bulletIndex) => (
                    <li key={bulletIndex}>
                      <strong>{bullet.label}</strong> {bullet.value}
                    </li>
                  ))}
                </ul>
              )}

              {section.privacyBefore && (
                <p>
                  {section.privacyBefore}
                  <a
                    href="#privacy"
                    onClick={(event) => {
                      event.preventDefault();
                      if (onShowPrivacy) onShowPrivacy();
                    }}
                  >
                    {section.privacyLink}
                  </a>
                  {section.privacyAfter}
                </p>
              )}
            </section>
          ))}

          <section className="contact-box">
            <h2>{content.contactTitle}</h2>
            <p>{content.contactText}</p>

            <button
              onClick={onContactClick}
              className="btn-contact-support"
              style={{
                marginTop: '15px',
                padding: '10px 20px',
                backgroundColor: '#3b82f6',
                color: 'white',
                border: 'none',
                borderRadius: '6px',
                cursor: 'pointer',
                fontWeight: 'bold'
              }}
            >
              {content.contactButton}
            </button>
          </section>
        </div>

        <footer className="terms-footer">
          {content.footer}
        </footer>
      </div>
    </div>
  );
};

export default LegalNoticePage;
